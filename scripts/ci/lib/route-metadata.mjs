import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { repoRoot } from "./repo.mjs";

const TREE_PATHS = {
  agent: "apps/web/src/routeTree.agent.gen.ts",
  portal: "apps/web/src/routeTree.portal.gen.ts",
};
export const METADATA_PATH = "apps/web/src/lib/generated-route-metadata.ts";

export function extractFullPaths(routeTree, sourcePath) {
  const block = routeTree.match(
    /export interface FileRouteTypes \{[\s\S]*?\n\s*fullPaths:\s*([\s\S]*?)\n\s*fileRoutesByTo:/u,
  )?.[1];
  if (!block)
    throw new Error(
      `${sourcePath} does not contain TanStack FileRouteTypes.fullPaths.`,
    );
  const paths = [...block.matchAll(/'([^']+)'/gu)].map((match) => match[1]);
  if (paths.length === 0)
    throw new Error(`${sourcePath} contains no generated file routes.`);
  return [...new Set(paths)].sort((left, right) => left.localeCompare(right));
}

export async function expectedRouteMetadata(root = repoRoot) {
  const result = {};
  for (const [surface, relativePath] of Object.entries(TREE_PATHS)) {
    const source = await readFile(path.join(root, relativePath), "utf8");
    result[surface] = extractFullPaths(source, relativePath);
  }
  return result;
}

export function renderRouteMetadata(metadata) {
  const entries = Object.entries(metadata).map(([surface, paths]) => {
    const inline = `  ${surface}: [${paths.map((route) => JSON.stringify(route)).join(", ")}],`;
    if (inline.length <= 80) return inline;
    return [
      `  ${surface}: [`,
      ...paths.map((route) => `    ${JSON.stringify(route)},`),
      "  ],",
    ].join("\n");
  });
  return [
    "// Generated by scripts/ci/generate-route-metadata.mjs from TanStack Router trees.",
    "// Do not edit by hand; check:inventory verifies this file against both trees.",
    "export const generatedRouteMetadata = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
}

export async function writeRouteMetadata(root = repoRoot) {
  const destination = path.join(root, METADATA_PATH);
  await writeFile(
    destination,
    renderRouteMetadata(await expectedRouteMetadata(root)),
  );
  return destination;
}
