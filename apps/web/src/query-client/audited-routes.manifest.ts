/**
 * Every API write that records a Settings History action (`apps/api/src/audit/history-actions.ts`),
 * mapped to the web code that calls it. `audited-routes.manifest.test.ts` checks it against the
 * source in both directions, so a new audited write, or a new caller of an audited fetcher, fails
 * the test until a mutation declares `meta.audits` for it. Tests import this file; the app never does.
 */
export type AuditedRoute = {
  /** `METHOD /path` under `/api`, as the web client calls it. */
  route: string;
  /** The `operationId` text that must appear in `api`. */
  op: string;
  /** Route file under `apps/api/src`. */
  api: string;
  /** Actions the route records. */
  actions: string[];
  /** Files under `apps/api/src` that write them; defaults to `[api]`. */
  producers?: string[];
  /** Web fetchers (`path#function`, `#default` for a default export) that call the route. */
  fetchers: string[];
  /** Web files under `apps/web/src` whose `useMutation` blocks must declare `meta.audits`. */
  mutations: string[];
  /** Why the route has no web caller at all. */
  noWeb?: string;
  /** Why the mutations cannot name a History target (they then need no `audits:`). */
  noTarget?: string;
};

/** Audit writes that no screen mutation causes directly, or that run on another trigger. */
export type AuditWriter = {
  why: string;
  producers: string[];
  actions: string[];
  /** Web mutations that also carry the refresh for this writer. */
  mutations?: string[];
};

